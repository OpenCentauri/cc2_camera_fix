# ---------------------------------------------------------------------------
# Deliberately narrow recovery use of the vendor's shell-injection bug
# ---------------------------------------------------------------------------
#
# Binary anchors:
#   target parsing  0x00402e3c
#   upload commit   0x004029f0
#
# The generic build_upload_target_request() below intentionally rejects shell
# metacharacters.  Weakening that validation would turn every caller into a
# potential command-injection producer.  This one immutable target is exposed
# separately because it is useful for a specific, audited recovery operation:
# start the stock /bin/adbd once without creating a persistent startup file.
#
# The target contains no literal spaces because hid_update truncates the target
# at the first ASCII space.  On 0x3300, its unquoted `system("rm %s")` becomes:
#
#   rm /tmp/.cc2flash-adbd-bootstrap;/bin/adbd&
#
# The following fopen() receives the *literal* full target.  Its embedded
# `/bin/...` makes `/tmp/.cc2flash-adbd-bootstrap;` an intermediate directory;
# that directory does not exist on the stock tmpfs, so fopen fails after adbd
# has already been launched.  This expected commit failure also prevents the
# later unquoted chmod command from launching adbd a second time.
#
# This is firmware-specific behavior, not a general shell-command API.  Keep
# the value constant, below the daemon's 128-byte target buffer, and free of
# literal whitespace.
# Keep the hardware-validated wire payload independent of the CLI name.
ADB_UPLOAD_COMMAND_TARGET = b"/tmp/.cc2flash-adbd-bootstrap;/bin/adbd&"


def build_adb_upload_command_target_request() -> bytes:
    """Build the one audited 0x3110 target that starts stock ``/bin/adbd``.

    Building the report performs no I/O.  Sending it as part of an upload
    transaction deliberately relies on the analyzed daemon's unquoted shell
    command.  Callers must expect the later 0x3300 commit to fail or disconnect
    after the process has been started.
    """

    assert b" " not in ADB_UPLOAD_COMMAND_TARGET
    assert 0 < len(ADB_UPLOAD_COMMAND_TARGET) <= 127
    return build_normal_report(
        NormalCommand.UPLOAD_TARGET_3110,
        ADB_UPLOAD_COMMAND_TARGET,
    )


def build_upload_initialize_request() -> bytes:
    """Build 0x3000, valid only while the device uploader is idle."""

    return build_normal_report(NormalCommand.UPLOAD_INITIALIZE)


def build_upload_target_request(
    command: NormalCommand | int,
    path: str | bytes | bytearray | memoryview | None = None,
) -> bytes:
    """Build any of the ten recovered destination-selection commands.

    The eight literal-path commands require a 1..127 byte safe ASCII path.  The
    two sensor-derived commands (0x3114/0x3115) require ``path=None`` because the
    camera constructs their paths from ``sensor_name``.  This intentionally
    excludes spaces and shell metacharacters that the vulnerable target would
    otherwise interpolate into unquoted ``rm`` and ``chmod`` commands.
    """

    try:
        selected = NormalCommand(command)
    except (TypeError, ValueError) as exc:
        raise ProtocolError(f"unknown upload target command: {command!r}") from exc

    if selected in DERIVED_UPLOAD_TARGET_COMMANDS:
        if path is not None:
            raise ProtocolError("sensor-derived upload target must not include a path")
        return build_normal_report(selected)
    if selected not in LITERAL_UPLOAD_TARGET_COMMANDS:
        raise ProtocolError(f"0x{int(selected):04x} is not an upload target command")
    if path is None:
        raise ProtocolError("literal upload target requires a path")

    try:
        encoded = path.encode("ascii") if isinstance(path, str) else bytes(path)
    except (UnicodeEncodeError, TypeError) as exc:
        raise ProtocolError("upload path must be ASCII or bytes-like") from exc
    if not encoded or len(encoded) > 127 or _SAFE_UPLOAD_PATH.fullmatch(encoded) is None:
        raise ProtocolError("upload path must be 1-127 safe ASCII path bytes")
    return build_normal_report(selected, encoded)


def build_upload_data_request(
    sequence: int,
    data: bytes | bytearray | memoryview,
    *,
    final: bool,
) -> bytes:
    """Build 0x3200 with its absolute sequence in the auxiliary field.

    Sequence values are absolute and zero-based.  A nonfinal frame is type 1;
    a final frame is type 2 and moves the target to ready-to-commit.  Zero-byte
    data is representable by the firmware and therefore remains representable
    here, although the high-level ``upload_normal_file`` helper rejects empty
    complete files as a separate policy decision.
    """

    if not isinstance(sequence, int) or not 0 <= sequence <= 0xFFFFFFFF:
        raise ProtocolError("upload sequence must fit in an unsigned 32-bit integer")
    try:
        payload = bytes(data)
    except TypeError as exc:
        raise ProtocolError("upload data must be bytes-like") from exc
    return build_normal_report(
        NormalCommand.UPLOAD_APPEND_DATA,
        payload,
        frame_type=int(
            NormalFrameType.FINAL_PAYLOAD if final else NormalFrameType.PAYLOAD_OR_CONTINUATION
        ),
        status=sequence,
    )


def build_upload_commit_request() -> bytes:
    """Build destructive 0x3300; valid only after a final data packet."""

    return build_normal_report(NormalCommand.UPLOAD_COMMIT)


def build_upgrade_request(
    *,
    mode: int = UPGRADE_MODE_HID,
    command: int = NormalCommand.UPGRADE_AND_REBOOT,
) -> bytes:
    """Build the exact eight-byte persistent upgrade-word write and reboot.

    The conventional command is 0x4000, but static analysis proves that every
    0x4xxx value reaches the same branch and echoes the actual value in its
    response.  ``mode`` may select the U-Boot HID or CDC transport.  Building
    this report is harmless; sending it writes flash offset 0x7f8000 and reboots.
    """

    if not is_upgrade_trigger_command(command):
        raise ProtocolError("upgrade trigger command must be in the 0x4xxx group")
    return build_normal_report(command, upgrade_flag_payload(mode))


# ---------------------------------------------------------------------------
# U-Boot updater frame types and typed helpers
# ---------------------------------------------------------------------------
#
# Binary anchor: common updater state machine at U-Boot 0x80117d1c.
#
# U-Boot has no general command word.  The byte at common-frame offset 3 is the
# entire operation namespace.  Only host types 1 and 3 are accepted.  Types 2
# and 5 are device replies.  There is no read, query, cancel, erase-only, reboot,
# partition-selection, signature, or post-write-verification frame type.


class BootFrameType(IntEnum):
    HOST_TRANSFER_METADATA = 1
    DEVICE_NEXT_PACKET_ACK = 2
    HOST_TRANSFER_DATA = 3
    DEVICE_TERMINAL_STATUS = 5


@dataclass(frozen=True)
class BootFrameTypeDescriptor:
    frame_type: BootFrameType
    direction: str
    payload: str
    meaning: str
    source_anchor: str


BOOT_FRAME_TYPES = (
    BootFrameTypeDescriptor(
        BootFrameType.HOST_TRANSFER_METADATA,
        "host -> device",
        "exactly 10 bytes",
        "initialize firmware transfer",
        "U-Boot type-1 branch 0x80117d1c",
    ),
    BootFrameTypeDescriptor(
        BootFrameType.DEVICE_NEXT_PACKET_ACK,
        "device -> host",
        "u32le(next expected absolute packet)",
        "acknowledge or request retransmission",
        "U-Boot send_ack path",
    ),
    BootFrameTypeDescriptor(
        BootFrameType.HOST_TRANSFER_DATA,
        "host -> device",
        "u32le(sequence) plus data",
        "append numbered transfer data",
        "U-Boot type-3 branch 0x80118094",
    ),
    BootFrameTypeDescriptor(
        BootFrameType.DEVICE_TERMINAL_STATUS,
        "device -> host",
        "one byte: 01 success, 00 failure",
        "RAM-image MD5 result, sent before flash erase/write",
        "U-Boot finalization 0x801183b0",
    ),
)


def build_boot_metadata_request(plan: UpdatePlan, *, firmware_version: int = 0) -> bytes:
    """Build the canonical 17-byte host type-1 metadata frame.

    U-Boot itself fails to reject zero divisors or oversized unauthenticated
    allocations.  The public producer closes those holes before serializing a
    frame and also checks that the redundant packet count in ``UpdatePlan`` is
    internally consistent.
    """

    if not 1 <= plan.packet_payload_size <= BOOT_DATA_SIZE:
        raise ProtocolError(
            f"metadata packet payload must be 1..{BOOT_DATA_SIZE} bytes for HID"
        )
    if not 1 <= plan.transfer_size <= 0xFFFFFFFF:
        raise ProtocolError("metadata transfer size must fit in a nonzero u32")
    if not 1 <= plan.packets_per_ack <= 0xFFFF:
        raise ProtocolError("metadata packets-per-ACK must fit in a nonzero u16")
    if not 0 <= firmware_version <= 0xFFFF:
        raise ProtocolError("metadata firmware version must fit in a u16")
    expected_packets = (
        plan.transfer_size + plan.packet_payload_size - 1
    ) // plan.packet_payload_size
    if plan.packet_count != expected_packets:
        raise ProtocolError(
            f"metadata packet count {plan.packet_count} does not match {expected_packets}"
        )

    return build_metadata_frame(plan, firmware_version=firmware_version)


def build_boot_data_request(
    sequence: int,
    data: bytes | bytearray | memoryview,
) -> bytes:
    """Build one host type-3 frame with an absolute packet sequence number."""

    if not isinstance(sequence, int) or not 0 <= sequence <= 0xFFFFFFFF:
        raise ProtocolError("bootloader sequence must fit in an unsigned 32-bit integer")
    try:
        payload = bytes(data)
    except TypeError as exc:
        raise ProtocolError("bootloader data must be bytes-like") from exc
    if len(payload) > BOOT_DATA_SIZE:
        raise ProtocolError(f"bootloader data exceeds the HID maximum of {BOOT_DATA_SIZE} bytes")
    return build_boot_frame(
        BootFrameType.HOST_TRANSFER_DATA,
        struct.pack("<I", sequence) + payload,
    )


def _coerce_device_boot_frame(frame: BootFrame | bytes) -> BootFrame:
    if isinstance(frame, BootFrame):
        return frame
    if not isinstance(frame, bytes):
        raise ProtocolError("bootloader response must be BootFrame or bytes")
    # A full HID response begins with report ID 1.  A bare common frame begins
    # with device magic 81 00 ee.  Parsing the two forms separately prevents the
    # report ID from being mistaken for part of the updater frame.
    if len(frame) >= 4 and frame[0] == 1 and frame[1:4] == b"\x81\x00\xee":
        return from_boot_hid_report(frame)
    return parse_boot_frame(frame, device_response=True)


def decode_boot_ack(frame: BootFrame | bytes) -> int:
    """Return the authoritative next expected packet from a type-2 reply."""

    parsed = _coerce_device_boot_frame(frame)
    if parsed.frame_type != BootFrameType.DEVICE_NEXT_PACKET_ACK:
        raise ProtocolError(f"expected bootloader type 2 ACK, got type {parsed.frame_type}")
    if len(parsed.payload) != 4:
        raise ProtocolError("bootloader type 2 ACK payload must be exactly four bytes")
    return struct.unpack("<I", parsed.payload)[0]


def decode_boot_terminal_status(frame: BootFrame | bytes) -> bool:
    """Decode type 5; true means received RAM bytes passed header MD5.

    This does *not* prove that SPI erase/write has completed or succeeded.  The
    bootloader sends the success byte first, waits roughly 200 ms, then programs
    flash without checking or reporting the driver return values.
    """

    parsed = _coerce_device_boot_frame(frame)
    if parsed.frame_type != BootFrameType.DEVICE_TERMINAL_STATUS:
        raise ProtocolError(f"expected bootloader type 5 status, got type {parsed.frame_type}")
    if parsed.payload not in (b"\x00", b"\x01"):
        raise ProtocolError("bootloader type 5 payload must be one byte 00 or 01")
    return parsed.payload == b"\x01"

