@dataclass(frozen=True)
class NormalCommandDescriptor:
    command: int
    name: str
    family: NormalCommandFamily
    request: str
    success_response: str
    side_effect: str
    source_anchor: str


def _build_normal_catalog() -> tuple[NormalCommandDescriptor, ...]:
    entries = [
        NormalCommandDescriptor(
            NormalCommand.VERSION_QUERY,
            "version_query",
            NormalCommandFamily.VERSION,
            "empty payload (extra bytes are ignored by firmware)",
            "type 1, status 0, first line of /tmp/version.txt",
            "none",
            "hid_update 0x004015e4",
        )
    ]
    for pair in CONFIGURATION_COMMANDS:
        entries.extend(
            (
                NormalCommandDescriptor(
                    pair.get,
                    f"config_get_{pair.key.value}",
                    NormalCommandFamily.CONFIGURATION,
                    "empty payload (payload is ignored)",
                    "type 1, status 0, raw value bytes",
                    "none",
                    "hid_update GET 0x00401cd0 / dispatcher 0x004024c0",
                ),
                NormalCommandDescriptor(
                    pair.set,
                    f"config_set_{pair.key.value}",
                    NormalCommandFamily.CONFIGURATION,
                    "replacement value bytes; frame type 1 or 2",
                    "type 0, status 0",
                    f"rewrites {pair.key.value} in persistent uvc.config",
                    "hid_update SET 0x00402038 / dispatcher 0x004024c0",
                ),
            )
        )
    for upload in UPLOAD_COMMANDS:
        entries.append(
            NormalCommandDescriptor(
                upload.command,
                upload.command.name.lower(),
                NormalCommandFamily.FILE_UPLOAD,
                upload.operation,
                "type 0, status 0 (wrong-state calls can falsely succeed)",
                "destructive file replacement" if upload.destructive else "changes uploader state or buffers data",
                "hid_update dispatcher 0x00402e3c",
            )
        )
    entries.append(
        NormalCommandDescriptor(
            NormalCommand.UPGRADE_AND_REBOOT,
            "upgrade_and_reboot",
            NormalCommandFamily.UPGRADE_TRIGGER,
            "exactly 8 upgrade-word bytes; canonical command 0x4000",
            "type 0, status 0 on write success; reboot follows even on failure",
            "writes flash 0x7f8000 and reboots into U-Boot updater",
            "hid_update 0x00401364; group branch 0x0040123c",
        )
    )
    return tuple(entries)


NORMAL_COMMAND_CATALOG = _build_normal_catalog()
NORMAL_COMMAND_BY_VALUE: Mapping[int, NormalCommandDescriptor] = MappingProxyType(
    {int(entry.command): entry for entry in NORMAL_COMMAND_CATALOG}
)


def is_upgrade_trigger_command(command: int) -> bool:
    """Return true for every value routed to the destructive 0x4xxx branch."""

    return isinstance(command, int) and 0 <= command <= 0xFFFF and command & 0xF000 == 0x4000


def describe_normal_command(command: int) -> NormalCommandDescriptor | None:
    """Describe an exact recovered command, including noncanonical 0x4xxx.

    ``None`` means the value has no implemented command handler.  Consult
    ``NORMAL_DISPATCH_MAP`` to distinguish silent no-op/no-response values from
    values that elicit status 5.
    """

    exact = NORMAL_COMMAND_BY_VALUE.get(command)
    if exact is not None:
        return exact
    if is_upgrade_trigger_command(command):
        canonical = NORMAL_COMMAND_BY_VALUE[int(NormalCommand.UPGRADE_AND_REBOOT)]
        return NormalCommandDescriptor(
            command,
            f"upgrade_and_reboot_0x{command:04x}",
            canonical.family,
            canonical.request,
            canonical.success_response,
            canonical.side_effect,
            canonical.source_anchor,
        )
    return None


# ---------------------------------------------------------------------------
# Side-effect-free normal-report builders
# ---------------------------------------------------------------------------


def _raw_payload(value: str | bytes | bytearray | memoryview, *, field: str) -> bytes:
    if isinstance(value, str):
        return value.encode("utf-8")
    if isinstance(value, (bytes, bytearray, memoryview)):
        return bytes(value)
    raise ProtocolError(f"{field} must be str or bytes-like")


def _configuration_pair(key: ConfigurationKey | str) -> ConfigCommandPair:
    try:
        normalized = key if isinstance(key, ConfigurationKey) else ConfigurationKey(key)
    except (TypeError, ValueError) as exc:
        raise ProtocolError(f"unknown configuration key: {key!r}") from exc
    return CONFIGURATION_BY_KEY[normalized]


def build_version_request() -> bytes:
    """Build exact command 0x0001; the request needs no payload."""

    return build_normal_report(NormalCommand.VERSION_QUERY)


def build_config_get_request(key: ConfigurationKey | str) -> bytes:
    """Build the even GET command for one recovered configuration key."""

    return build_normal_report(_configuration_pair(key).get)


def build_config_set_request(
    key: ConfigurationKey | str,
    value: str | bytes | bytearray | memoryview,
    *,
    frame_type: NormalFrameType = NormalFrameType.PAYLOAD_OR_CONTINUATION,
) -> bytes:
    """Build the odd SET command without guessing the value's semantics.

    UTF-8 is used when ``value`` is a string.  Bytes-like input is preserved
    exactly.  The target does no validation and has unsafe fixed buffers, so the
    caller remains responsible for choosing a short, appropriate textual value.
    """

    return build_normal_report(
        _configuration_pair(key).set,
        _raw_payload(value, field="configuration value"),
        frame_type=int(frame_type),
    )


