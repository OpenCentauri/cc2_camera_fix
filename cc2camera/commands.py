# ---------------------------------------------------------------------------
# Normal Linux HID: framing vocabulary and dispatcher behavior
# ---------------------------------------------------------------------------
#
# Binary anchor: hid_update dispatch_normal_report() at 0x0040123c.
#
# Requests and responses are 1,024 bytes.  The request field at offset 8 is an
# auxiliary value (used as the absolute upload-packet number by 0x3200); the
# same four bytes are a status code in replies.  Frame type 1 means a normal or
# continuing payload and type 2 marks the final upload packet.  Although the
# target parser fails to reject other type values, those values remove payload
# bytes from CRC coverage and must never be emitted by this library.


class NormalFrameType(IntEnum):
    """Only the two request frame types safe for a producer to emit."""

    PAYLOAD_OR_CONTINUATION = 1
    FINAL_PAYLOAD = 2


class NormalStatus(IntEnum):
    """Status values generated by the Linux daemon's response constructor."""

    SUCCESS = 0
    HANDLER_FAILURE = 1
    BAD_REPORT_ID = 2
    BAD_MAGIC = 3
    BAD_CRC = 4
    UNKNOWN_COMMAND_GROUP = 5


class NormalCommandFamily(str, Enum):
    VERSION = "version"
    CONFIGURATION = "configuration"
    FILE_UPLOAD = "file-upload"
    UPGRADE_TRIGGER = "upgrade-trigger"


@dataclass(frozen=True)
class NormalDispatchBehavior:
    """One high-level branch of the normal-mode command dispatcher."""

    first: int
    last: int
    behavior: str
    response_behavior: str


# This range table is intentionally explicit.  It records negative behavior as
# well as useful commands: 0x1xxx is a silent no-op, unknown values inside the
# 0x2xxx/0x3xxx groups are silent, every 0x4xxx value is destructive, and higher
# groups return status 5.  A host must therefore use timeouts for silent paths.
NORMAL_DISPATCH_MAP = (
    NormalDispatchBehavior(0x0000, 0x0FFF, "only exact 0x0001 is implemented", "other values: no response"),
    NormalDispatchBehavior(0x1000, 0x1FFF, "recognized no-op group", "no response"),
    NormalDispatchBehavior(0x2000, 0x2FFF, "listed configuration commands only", "unknown values: no response"),
    NormalDispatchBehavior(0x3000, 0x3FFF, "listed upload commands only", "unknown values: no response"),
    NormalDispatchBehavior(0x4000, 0x4FFF, "write upgrade words and reboot", "status 0/1, then reboot"),
    NormalDispatchBehavior(0x5000, 0xFFFF, "unknown command group", "status 5"),
)


