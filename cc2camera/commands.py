# ---------------------------------------------------------------------------
# Complete configuration GET/SET table
# ---------------------------------------------------------------------------
#
# Binary anchors: dispatch table at 0x004024c0, GET at 0x00401cd0, and SET at
# 0x00402038.  Every even command reads one literal key from
# /etc/conf.d/uvc.config; the following odd command rewrites that key.
#
# The target performs no type, range, or encoding validation.  Its SET routine
# uses undersized fixed buffers and zero-pads instead of truncating when a new
# value is shorter.  The builders preserve the raw protocol but callers should
# send short textual values only.  A builder succeeding says nothing about the
# semantic safety of the value or whether the key exists on a particular unit.


